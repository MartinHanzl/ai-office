#!/usr/bin/env node
'use strict';
/**
 * Copies the two ASCII floor plans (and the legend) from docs/office/layout.md into
 * renderer/src/world/maps.js. The markdown stays the single source of truth; run
 * `npm run sync-maps` after every edit of the plans.
 */
const fs = require('node:fs');
const path = require('node:path');

const ROWS = 45;
const COLS = 80;
const root = path.join(__dirname, '..');
const src = path.join(root, 'docs', 'office', 'layout.md');
const out = path.join(root, 'renderer', 'src', 'world', 'maps.js');

const md = fs.readFileSync(src, 'utf8');
const lines = md.split('\n');

/** Fenced block lines that follow the first heading matching `re`. */
function blockAfter(re) {
  const start = lines.findIndex((l) => /^#{2,3} /.test(l) && re.test(l));
  if (start < 0) throw new Error(`layout.md: no heading matching ${re}`);
  const open = lines.findIndex((l, i) => i > start && l.startsWith('```'));
  const close = lines.findIndex((l, i) => i > open && l.startsWith('```'));
  if (open < 0 || close < 0) throw new Error(`layout.md: no fenced map after "${lines[start]}"`);
  return lines.slice(open + 1, close);
}

/** Strips the two ruler lines and the "NN " row prefixes; asserts the size. */
function parseMap(name, block) {
  const rows = [];
  for (const line of block) {
    const m = /^(\d\d) (.*)$/.exec(line.replace(/\s+$/, ''));
    if (!m) continue; // ruler lines start with spaces
    if (Number(m[1]) !== rows.length) throw new Error(`${name}: row ${m[1]} out of order (expected ${rows.length})`);
    rows.push(m[2]);
  }
  if (rows.length !== ROWS) throw new Error(`${name}: ${rows.length} rows, expected ${ROWS}`);
  rows.forEach((r, i) => {
    if ([...r].length !== COLS) throw new Error(`${name}: row ${i} has ${[...r].length} chars, expected ${COLS}`);
  });
  return rows;
}

/** Legend table of section 1: char → description (cells with several chars give each the same text). */
function parseLegend() {
  const legend = {};
  const start = lines.findIndex((l) => /^## 1\b/.test(l));
  for (let i = start + 1; i < lines.length && !/^## /.test(lines[i]); i++) {
    const cells = lines[i].split(/(?<!\\)\|/).slice(1, -1).map((c) => c.trim());
    if (cells.length < 2) continue;
    const chars = [...cells[0].matchAll(/`([^`]+)`/g)].map((m) => m[1].replace(/^\\(?=.)/, ''));
    for (const ch of chars) if ([...ch].length === 1) legend[ch] = cells[1].replace(/\*\*/g, '');
  }
  return legend;
}

const version = /\(návrh (v\d+)\)/.exec(lines[0])?.[1] ?? /\bv(\d+)\b/.exec(lines[0])?.[0] ?? 'unknown';
const ground = parseMap('ground', blockAfter(/Přízemí/i));
const upper = parseMap('upper', blockAfter(/Horní patro/i));
const legend = parseLegend();

const unknown = new Set();
for (const row of [...ground, ...upper]) for (const ch of row) if (!(ch in legend)) unknown.add(ch);

const arr = (rows) => `[\n${rows.map((r) => `    ${JSON.stringify(r)},`).join('\n')}\n  ]`;
const body = `/**
 * Floor plans of the BlueGhost office, generated by scripts/sync-maps.js from
 * docs/office/layout.md (${version}). Do not edit – change the markdown and run \`npm run sync-maps\`.
 * One char per 4×4 px cell, ${ROWS} rows × ${COLS} cols; rows 0–11 are the back-wall band.
 */

export const MAP_VERSION = ${JSON.stringify(version)};

export const MAPS = {
  ground: ${arr(ground)},
  upper: ${arr(upper)},
};

/** Legend of layout.md section 1 (char → meaning, Czech). */
export const LEGEND = ${JSON.stringify(legend, null, 2).replace(/\n/g, '\n')};
`;

fs.writeFileSync(out, body);
console.log(`✔ maps ${version} → ${path.relative(root, out)} (${ROWS}×${COLS}, ${Object.keys(legend).length} legend chars)`);
if (unknown.size) console.warn(`⚠ chars missing from the legend: ${[...unknown].map((c) => JSON.stringify(c)).join(' ')}`);
